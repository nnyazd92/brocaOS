# Configurable paths (relative to repo root by default)
REPO_ROOT = Path.cwd()
SHUTDOWN_JSON = REPO_ROOT / ".shutdown_persistence.json"
ENV_FILE = REPO_ROOT / ".env"
ARTIFACTS_DIR = REPO_ROOT / "docs" / "external_artifacts" / "home_wizard_broca" / "artifacts"
REHYDRATION_ARTIFACT = ARTIFACTS_DIR / "REHYDRATION_SUMMARY.v0.2.md"
